//! The generated API reference pages of the documentation book.
//!
//! The vendored specification is the source of truth for the operations the
//! SDK covers. The task turns it into two Markdown pages — one per book
//! language — that list every operation with its HTTP method, its path, the
//! name of the generated function and the summary of the vendor.
//!
//! The pages are committed, and the documentation workflow checks that they
//! match the specification.

use std::{collections::BTreeMap, fs};

use masterror::AppResult;
use serde_json::{Map, Value};

use crate::paths;

/// The HTTP methods the specification describes operations for.
const HTTP_METHODS: [&str; 5] = ["get", "post", "put", "patch", "delete"];

/// The header of the generated page.
const HEADER: &str = "\
<!-- Generated by `cargo xtask api-index` from the vendored OpenAPI specification. -->
";

/// One operation of the specification.
struct Operation {
    /// The HTTP method of the operation.
    method:   String,
    /// The route of the operation.
    path:     String,
    /// The name of the generated function.
    function: String,
    /// The summary the vendor documents for the operation.
    summary:  String,
    /// The API area the operation belongs to.
    area:     String
}

/// The feature that compiles the API area.
fn feature_name(area: &str) -> String {
    let mut name = String::new();
    let mut separator = false;
    for character in area.chars() {
        if character.is_ascii_alphanumeric() {
            if separator && !name.is_empty() {
                name.push('-');
            }
            separator = false;
            name.push(character.to_ascii_lowercase());
            continue;
        }
        separator = true;
    }
    name
}

/// The English name of the area an operation belongs to.
///
/// The vendor writes the tags in Russian and keeps the English name in
/// `x-tags-i18n`; the English name is the one the API areas are named after.
fn area_of(operation: &Map<String, Value>) -> String {
    let english = operation
        .get("x-tags-i18n")
        .and_then(|value| value.get("eng"))
        .and_then(Value::as_array)
        .and_then(|tags| tags.first())
        .and_then(Value::as_str);
    english
        .or_else(|| {
            operation
                .get("tags")
                .and_then(Value::as_array)
                .and_then(|tags| tags.first())
                .and_then(Value::as_str)
        })
        .unwrap_or("default")
        .to_string()
}

/// Collects every operation of the specification.
fn collect_operations(spec: &Value) -> Vec<Operation> {
    let mut operations = Vec::new();
    let Some(paths) = spec.get("paths").and_then(Value::as_object) else {
        return operations;
    };
    for (path, methods) in paths {
        let Some(methods) = methods.as_object() else {
            continue;
        };
        for (method, operation) in methods {
            if !HTTP_METHODS.contains(&method.as_str()) {
                continue;
            }
            let Some(operation) = operation.as_object() else {
                continue;
            };
            let Some(function) = operation.get("operationId").and_then(Value::as_str) else {
                continue;
            };
            let area = area_of(operation);
            operations.push(Operation {
                method: method.to_uppercase(),
                path: path.clone(),
                function: function.to_string(),
                summary: operation
                    .get("summary")
                    .and_then(Value::as_str)
                    .unwrap_or_default()
                    .to_string(),
                area
            });
        }
    }
    operations.sort_by(|left, right| {
        left.area
            .cmp(&right.area)
            .then_with(|| left.path.cmp(&right.path))
            .then_with(|| left.method.cmp(&right.method))
    });
    operations
}

/// Renders the page of the API reference.
///
/// # Arguments
///
/// * `operations` — the operations of the specification.
/// * `language` — the code of the book language the page belongs to.
///
/// # Returns
///
/// The Markdown page.
fn render(operations: &[Operation], language: &str) -> String {
    let heading = if language == "ru" {
        "Справочник API"
    } else {
        "API reference"
    };
    let intro = if language == "ru" {
        format!(
            "SDK покрывает **{} операций** в **{} области** API Timeweb Cloud. \
             Каждая область компилируется, только если включён её флаг Cargo, \
             поэтому лишние модели не попадают в сборку. Описания операций взяты \
             из спецификации вендора.",
            operations.len(),
            operations
                .iter()
                .map(|operation| operation.area.as_str())
                .collect::<std::collections::BTreeSet<_>>()
                .len()
        )
    } else {
        format!(
            "The SDK covers **{} operations** across **{} areas** of the Timeweb Cloud \
             API. Every area is compiled only when its Cargo feature is enabled, so \
             a consumer that needs one area does not compile the rest. The \
             summaries are quoted from the vendor's specification.",
            operations.len(),
            operations
                .iter()
                .map(|operation| operation.area.as_str())
                .collect::<std::collections::BTreeSet<_>>()
                .len()
        )
    };

    let mut areas: BTreeMap<&str, Vec<&Operation>> = BTreeMap::new();
    for operation in operations {
        areas
            .entry(operation.area.as_str())
            .or_default()
            .push(operation);
    }

    let mut page = String::from(HEADER);
    page.push_str(&format!("# {heading}\n\n{intro}\n\n"));
    for (area, operations) in areas {
        let feature = feature_name(area);
        page.push_str(&format!(
            "## {area}\n\nCargo feature: `{feature}` · operations: {}\n\n",
            operations.len()
        ));
        page.push_str("| Method | Path | Function | Summary |\n");
        page.push_str("| --- | --- | --- | --- |\n");
        for operation in operations {
            let summary = operation.summary.replace('|', "\\|");
            page.push_str(&format!(
                "| `{}` | `{}` | `{}` | {summary} |\n",
                operation.method, operation.path, operation.function
            ));
        }
        page.push('\n');
    }
    page
}

/// The paths of the generated pages.
fn page_paths() -> Vec<(std::path::PathBuf, &'static str)> {
    vec![
        (paths::repo_root().join("docs/en/src/api-index.md"), "en"),
        (paths::repo_root().join("docs/ru/src/api-index.md"), "ru"),
    ]
}

/// Regenerates the API reference pages of the book.
///
/// # Arguments
///
/// * `check` — fail instead of rewriting the pages when they are stale.
///
/// # Errors
///
/// Returns an error when the specification cannot be read, when a page cannot
/// be written or when a page is stale and `check` is set.
pub fn regenerate(check: bool) -> AppResult<()> {
    let text = fs::read_to_string(paths::spec_file())?;
    let spec: Value = serde_json::from_str(&text)?;
    let operations = collect_operations(&spec);
    if operations.is_empty() {
        return Err(crate::spec::spec_error(
            "the specification does not describe any operation"
        ));
    }

    for (path, language) in page_paths() {
        let page = render(&operations, language);
        if check {
            let current = fs::read_to_string(&path).unwrap_or_default();
            if current != page {
                return Err(crate::spec::spec_error(format!(
                    "{} is stale; run `cargo xtask api-index`",
                    path.display()
                )));
            }
            continue;
        }
        fs::write(&path, page)?;
    }
    if !check {
        println!(
            "wrote the API reference for {} operations",
            operations.len()
        );
    }
    Ok(())
}
