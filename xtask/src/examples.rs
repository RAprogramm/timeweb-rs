//! Regeneration of the deserialization tests built from the spec examples.
//!
//! Every `application/json` response example in the vendored `OpenAPI` spec is
//! evidence of a body the API is documented to produce. This module emits one
//! integration test per example asserting that the corresponding generated
//! model still deserializes it, and writes them to
//! `tests/generated_spec_examples.rs` as a committed, self-contained file
//! (the example bodies are inlined, so the published crate's tests do not
//! depend on the spec file, which is excluded from the package).
//!
//! Target model resolution treats the generated code as the source of truth:
//!
//! * a success (2xx) example maps to the return type of the generated function
//!   for its operation, read from the `Result<models::X, _>` signatures in
//!   `src/apis` — this survives both the generator's abbreviation casing and
//!   its deduplication of identical inline schemas (several operations can
//!   share one response model);
//! * an error example maps to a `$ref`'d component model or to the
//!   `{OperationId}{Status}Response` inline-schema convention, validated
//!   against the exports of `src/models/mod.rs`, and is skipped with a notice
//!   when neither resolves (error shapes are aggressively deduplicated and
//!   carry little unique structure).
//!
//! A success example whose operation cannot be found in `src/apis` is a real
//! drift signal: it is reported and the task fails so a regeneration cannot
//! quietly lose coverage.
//!
//! The vendor's examples are not always consistent with the vendor's own
//! schemas (naive datetimes in `date-time` fields, omitted required fields).
//! After emitting the file the tests are therefore run once and every failing
//! one is quarantined with `#[ignore]` and the reason, so CI stays green while
//! each mismatch stays visible in the committed file — and disappears from the
//! quarantine automatically once the spec (or the normalizer) fixes it.

use std::{collections::BTreeMap, fs, process::Command};

use masterror::AppResult;
use regex::Regex;
use serde_json::Value;

use crate::paths;

/// The header of the generated test file.
const HEADER: &str = "\
//! Deserialization tests generated from the OpenAPI response examples.
//!
//! Generated by `cargo xtask example-tests` — do not edit by hand;
//! regenerate after every spec update. Each test parses a response example
//! embedded in the vendored spec into the model the generator produced for
//! that response, pinning the spec, the normalizer and the generator
//! together: if a regeneration breaks deserialization of a documented
//! body, the update fails here instead of in production.
//!
//! Tests marked `#[ignore]` are quarantined: their example does not
//! deserialize because the vendor's example contradicts the vendor's own
//! schema (or the generated model). The quarantine is recomputed on every
//! regeneration, so a fixed example rejoins the active set automatically.

#![allow(clippy::needless_raw_string_hashes, clippy::doc_markdown)]
";

/// The reason written on every quarantined test.
const QUARANTINE_REASON: &str = "quarantined by the example-test generator: the spec's example does not deserialize into the \
     generated model";

/// The HTTP methods the specification describes operations for.
const HTTP_METHODS: [&str; 8] = [
    "get", "post", "put", "patch", "delete", "head", "options", "trace"
];

/// Splits a word into the chunks the generator's naming convention uses.
///
/// A run of uppercase letters forms one chunk unless a lowercase letter
/// follows it: `HTTPServer` becomes `HTTP` and `Server`, while `ID` stays
/// `ID`.
fn chunks(word: &str) -> Vec<String> {
    let characters: Vec<char> = word.chars().collect();
    let mut result = Vec::new();
    let mut index = 0;
    while index < characters.len() {
        let current = characters[index];
        if current.is_ascii_uppercase() {
            let mut end = index;
            while end < characters.len() && characters[end].is_ascii_uppercase() {
                end += 1;
            }
            let followed_by_lowercase = characters.get(end).is_some_and(char::is_ascii_lowercase);
            if !followed_by_lowercase {
                result.push(characters[index..end].iter().collect());
                index = end;
                continue;
            }
            if end - index > 1 {
                result.push(characters[index..end - 1].iter().collect());
                index = end - 1;
                continue;
            }
            let mut end = index + 1;
            while end < characters.len()
                && (characters[end].is_ascii_lowercase() || characters[end].is_ascii_digit())
            {
                end += 1;
            }
            result.push(characters[index..end].iter().collect());
            index = end;
            continue;
        }
        if current.is_ascii_lowercase() || current.is_ascii_digit() {
            let mut end = index;
            while end < characters.len()
                && (characters[end].is_ascii_lowercase() || characters[end].is_ascii_digit())
            {
                end += 1;
            }
            result.push(characters[index..end].iter().collect());
            index = end;
            continue;
        }
        index += 1;
    }
    result
}

/// Converts an operation id or a schema name to the generator's type name.
fn pascal(identifier: &str) -> String {
    let mut parts = Vec::new();
    for word in identifier.split(|character: char| !character.is_ascii_alphanumeric()) {
        if word.is_empty() {
            continue;
        }
        for chunk in chunks(word) {
            let mut characters = chunk.chars();
            let mut capitalized = String::new();
            if let Some(first) = characters.next() {
                capitalized.extend(first.to_uppercase());
                capitalized.push_str(characters.as_str());
            }
            parts.push(capitalized);
        }
    }
    parts.concat()
}

/// Converts a type or an operation name to a `snake_case` test identifier.
fn snake(identifier: &str) -> String {
    let pascal = pascal(identifier);
    let mut snake = String::new();
    let mut previous: Option<char> = None;
    for character in pascal.chars() {
        if character.is_uppercase()
            && previous
                .is_some_and(|previous| previous.is_ascii_lowercase() || previous.is_ascii_digit())
        {
            snake.push('_');
        }
        snake.push(character);
        previous = Some(character);
    }
    snake.to_lowercase()
}

/// The case- and separator-insensitive key used to match operation names.
fn normalize(identifier: &str) -> String {
    identifier
        .to_lowercase()
        .chars()
        .filter(char::is_ascii_alphanumeric)
        .collect()
}

/// The return model of every generated operation.
fn operation_return_models() -> AppResult<BTreeMap<String, String>> {
    let functions = Regex::new(r"pub async fn (\w+)").expect("valid pattern");
    let returns = Regex::new(r"(?s)->\s*Result<\s*models::(\w+)").expect("valid pattern");
    let mut mapping = BTreeMap::new();
    for entry in fs::read_dir(paths::apis_dir())? {
        let path = entry?.path();
        if path.extension().is_none_or(|extension| extension != "rs") {
            continue;
        }
        let text = fs::read_to_string(&path)?;
        let matches = functions
            .captures_iter(&text)
            .map(|capture| {
                let name = capture.get(1).map(|name| name.as_str().to_string());
                let start = capture.get(0).map_or(0, |found| found.start());
                (name, start)
            })
            .collect::<Vec<(Option<String>, usize)>>();
        for (index, (name, start)) in matches.iter().enumerate() {
            let end = match matches.get(index + 1) {
                Some((_, next)) => *next,
                None => text.len()
            };
            let Some(name) = name else {
                continue;
            };
            let body = &text[*start..end];
            if let Some(model) = returns.captures(body).and_then(|capture| capture.get(1)) {
                mapping.insert(normalize(name), model.as_str().to_string());
            }
        }
    }
    if mapping.is_empty() {
        return Err(crate::spec::spec_error(
            "no generated operation signatures found under src/apis"
        ));
    }
    Ok(mapping)
}

/// Every model type re-exported from `src/models/mod.rs`.
fn exported_models() -> AppResult<Vec<String>> {
    let text = fs::read_to_string(paths::models_module())?;
    let exports =
        Regex::new(r"pub use self::[A-Za-z0-9_]+::([A-Za-z0-9_]+);").expect("valid pattern");
    let models = exports
        .captures_iter(&text)
        .filter_map(|capture| capture.get(1))
        .map(|name| name.as_str().to_string())
        .collect::<Vec<String>>();
    if models.is_empty() {
        return Err(crate::spec::spec_error(
            "no model exports found in src/models/mod.rs"
        ));
    }
    Ok(models)
}

/// The response example of a specification response.
struct ResponseExample {
    /// The operation the response belongs to.
    operation_id: String,
    /// The name of the named example, empty for an inline one.
    variant:      String,
    /// The HTTP method of the operation.
    method:       String,
    /// The route of the operation.
    path:         String,
    /// The HTTP status of the response.
    status:       String,
    /// The example body.
    example:      Value,
    /// The schema the response documents.
    schema:       Value
}

/// Collects every JSON response example of the specification.
fn response_examples(spec: &Value) -> Vec<ResponseExample> {
    let mut found = Vec::new();
    let Some(paths) = spec.get("paths").and_then(Value::as_object) else {
        return found;
    };
    let mut routes: Vec<&String> = paths.keys().collect();
    routes.sort();
    for path in routes {
        let Some(methods) = paths.get(path).and_then(Value::as_object) else {
            continue;
        };
        for (method, operation) in methods {
            if !HTTP_METHODS.contains(&method.as_str()) {
                continue;
            }
            let Some(operation) = operation.as_object() else {
                continue;
            };
            let Some(operation_id) = operation.get("operationId").and_then(Value::as_str) else {
                continue;
            };
            let Some(responses) = operation.get("responses").and_then(Value::as_object) else {
                continue;
            };
            let mut statuses: Vec<&String> = responses.keys().collect();
            statuses.sort();
            for status in statuses {
                let Some(response) = responses.get(status) else {
                    continue;
                };
                let Some(content) = response
                    .get("content")
                    .and_then(|content| content.get("application/json"))
                else {
                    continue;
                };
                let schema = content.get("schema").cloned().unwrap_or(Value::Null);
                if let Some(single) = content.get("example") {
                    found.push(ResponseExample {
                        operation_id: operation_id.to_string(),
                        variant:      String::new(),
                        method:       method.clone(),
                        path:         (*path).clone(),
                        status:       (*status).clone(),
                        example:      single.clone(),
                        schema:       schema.clone()
                    });
                }
                if let Some(named) = content.get("examples").and_then(Value::as_object) {
                    let mut variants: Vec<&String> = named.keys().collect();
                    variants.sort();
                    for name in variants {
                        let Some(value) = named.get(name) else {
                            continue;
                        };
                        let Some(body) = value.get("value") else {
                            continue;
                        };
                        found.push(ResponseExample {
                            operation_id: operation_id.to_string(),
                            variant:      (*name).clone(),
                            method:       method.clone(),
                            path:         (*path).clone(),
                            status:       (*status).clone(),
                            example:      body.clone(),
                            schema:       schema.clone()
                        });
                    }
                }
            }
        }
    }
    found
}

/// The model an error response maps to when no signature applies.
fn error_model(operation_id: &str, status: &str, schema: &Value) -> String {
    if let Some(reference) = schema.get("$ref").and_then(Value::as_str) {
        let name = reference.rsplit('/').next().unwrap_or(reference);
        return pascal(name);
    }
    format!("{}{status}Response", pascal(operation_id))
}

/// Renders the test of a single example.
fn render_test(name: &str, model: &str, example: &Value, provenance: &str) -> String {
    let body = serde_json::to_string_pretty(example).unwrap_or_else(|_| "{}".to_string());
    format!(
        "#[test]\nfn {name}() {{\n    let body = r##\"\n{body}\n\"##;\n    let _: timeweb_rs::models::{model} = \
         serde_json::from_str(body)\n        .expect(\"spec example for {provenance} must deserialize\");\n}}\n",
    )
}

/// Runs the generated tests and returns the names of the failing ones.
fn run_tests() -> AppResult<Vec<String>> {
    let output = Command::new("cargo")
        .args(["test", "--test", "generated_spec_examples"])
        .current_dir(paths::repo_root())
        .output()?;
    let stdout = String::from_utf8_lossy(&output.stdout);
    let failing = Regex::new(r"(?m)^test (\w+) \.\.\. FAILED$")
        .expect("valid pattern")
        .captures_iter(&stdout)
        .filter_map(|capture| capture.get(1))
        .map(|name| name.as_str().to_string())
        .collect::<Vec<String>>();
    if !output.status.success() && failing.is_empty() {
        return Err(crate::spec::spec_error(format!(
            "the generated tests failed to build:\n{}",
            String::from_utf8_lossy(&output.stderr)
        )));
    }
    Ok(failing)
}

/// Regenerates the deserialization tests built from the spec examples.
///
/// # Errors
///
/// Returns an error when the specification cannot be read, when a documented
/// success example has no generated operation or when the tests cannot be
/// built.
pub fn regenerate() -> AppResult<()> {
    let text = fs::read_to_string(paths::spec_file())?;
    let spec: Value = serde_json::from_str(&text)?;
    let models = exported_models()?;
    let returns = operation_return_models()?;

    let mut tests = Vec::new();
    let mut seen: Vec<String> = Vec::new();
    let mut unresolved: Vec<String> = Vec::new();
    let mut skipped: Vec<String> = Vec::new();

    for example in response_examples(&spec) {
        let provenance = format!(
            "{} {} {}",
            example.method.to_uppercase(),
            example.path,
            example.status
        );
        let provenance = if example.variant.is_empty() {
            provenance
        } else {
            format!("{provenance} ({})", example.variant)
        };
        let model = if example.status.starts_with('2') {
            if let Some(model) = returns.get(&normalize(&example.operation_id)) {
                model.clone()
            } else {
                unresolved.push(format!(
                    "{provenance}: no generated operation for {}",
                    example.operation_id
                ));
                continue;
            }
        } else {
            let model = error_model(&example.operation_id, &example.status, &example.schema);
            if !models.contains(&model) {
                skipped.push(format!("{provenance}: no model named {model}"));
                continue;
            }
            model
        };
        let suffix = if example.variant.is_empty() {
            String::new()
        } else {
            format!("_{}", snake(&example.variant))
        };
        let mut name = format!(
            "{}_{}{suffix}_example_deserializes",
            snake(&example.operation_id),
            example.status
        );
        while seen.contains(&name) {
            name.push_str("_more");
        }
        seen.push(name.clone());
        tests.push(render_test(&name, &model, &example.example, &provenance));
    }

    for line in &skipped {
        eprintln!("skipping error example — {line}");
    }
    if !unresolved.is_empty() {
        eprintln!("success examples without a generated operation:");
        for line in &unresolved {
            eprintln!("  {line}");
        }
        return Err(crate::spec::spec_error(
            "the specification documents operations the generated client does not have"
        ));
    }

    let path = paths::example_tests();
    fs::write(&path, format!("{HEADER}\n{}", tests.join("\n")))?;
    let failing = run_tests()?;
    if !failing.is_empty() {
        let text = fs::read_to_string(&path)?;
        let mut text = text;
        for name in &failing {
            let declaration = format!("#[test]\nfn {name}(");
            let quarantined = format!("#[test]\n#[ignore = \"{QUARANTINE_REASON}\"]\nfn {name}(");
            text = text.replace(&declaration, &quarantined);
        }
        fs::write(&path, text)?;
        println!(
            "quarantined {} tests whose example does not deserialize:",
            failing.len()
        );
        for name in &failing {
            println!("  {name}");
        }
    }
    println!(
        "wrote {} tests to {} ({} active, {} quarantined)",
        tests.len(),
        path.display(),
        tests.len() - failing.len(),
        failing.len()
    );
    Ok(())
}
